def fact(row,a,r,b,quote,certainty='stated',nature='source_statement'):
    row['facts'].append(dict(a=a,r=r,b=b,quote=quote,certainty=certainty,nature=nature))
def chain(row,nodes,quote,certainty='stated'):
    for a,b in zip(nodes,nodes[1:]): fact(row,a,'CAUSES',b,quote,certainty)
def many(row,subjects,rel,obj,quote,certainty='possible'):
    for subject in subjects: fact(row,subject,rel,obj,quote,certainty)
def checks(row,items,quote):
    for name,target in items: fact(row,'C|'+name,'CHECKS',target,quote,nature='source_check')
def actions(row,items,quote):
    for name,target in items: fact(row,'A|'+name,'ADDRESSES',target,quote,nature='source_recommendation')

